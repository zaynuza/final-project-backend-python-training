"""Application: ports = interface yang dibutuhkan use case.
Implementasinya (adapter) ada di layer infrastructure.
"""
from typing import Protocol

from app.domain.order import Order
from app.domain.product import Product
from app.domain.user import User
from app.domain.voucher import Voucher


class OrderRepository(Protocol):
    def add(self, order: Order) -> Order: ...
    def get(self, order_id: int) -> Order | None: ...
    def get_for_update(self, order_id: int) -> Order | None: ...      # get + kunci baris sampai transaksi selesai
    def best_sellers(self, limit: int) -> list[dict]: ...
    def list_for_customer(self, customer: str, limit: int, after: int | None = None) -> list[Order]: ...
    def sales_summary(self) -> dict: ...
    def save(self, order: Order) -> None: ...


class ProductRepository(Protocol):
    def add(self, product: Product) -> Product: ...
    def get(self, product_id: int) -> Product | None: ...
    def get_for_update(self, product_id: int) -> Product | None: ...  # get + kunci baris (SELECT ... FOR UPDATE)
    def list(self) -> list[Product]: ...
    def save(self, product: Product) -> None: ...


class VoucherRepository(Protocol):
    def add(self, voucher: Voucher) -> Voucher: ...
    def get(self, code: str) -> Voucher | None: ...
    def get_for_update(self, code: str) -> Voucher | None: ...        # get + kunci baris (SELECT ... FOR UPDATE)
    def save(self, voucher: Voucher) -> None: ...


class UserRepository(Protocol):
    def add(self, user: User) -> User: ...
    def get_by_email(self, email: str) -> User | None: ...


class UnitOfWork(Protocol):
    """Satu transaksi. Keluar dari `with uow:` tanpa commit() = rollback."""
    orders: OrderRepository
    products: ProductRepository
    vouchers: VoucherRepository
    users: UserRepository

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exc) -> None: ...
    def commit(self) -> None: ...


class Cache(Protocol):
    """Penyimpanan sementara berbentuk key-value, nilai otomatis kedaluwarsa (TTL)."""
    def get(self, key: str): ...
    def set(self, key: str, value) -> None: ...
    def delete(self, *keys: str) -> None: ...
    def acquire_lock(self, key: str, ttl: int = 5) -> bool: ...   # True hanya untuk SATU pemanggil (SET NX EX)
    def release_lock(self, key: str) -> None: ...


class EventPublisher(Protocol):
    """Mengumumkan event ke message broker."""
    def publish(self, event: dict) -> None: ...


class Notifier(Protocol):
    def send(self, to: str, message: str) -> None: ...


class PointsLedger(Protocol):
    """Buku poin customer. add() mengembalikan False jika event_id sudah pernah dicatat."""
    def add(self, event_id: str, customer: str, points: int) -> bool: ...
    def balance(self, customer: str) -> int: ...


class NotificationLog(Protocol):
    """Catatan event yang notifikasinya sudah terkirim (idempotency)."""
    def already_sent(self, key: str) -> bool: ...
    def mark_sent(self, key: str) -> None: ...


class LoginAttemptLimiter(Protocol):
    """Membatasi login gagal per email (melawan brute force). Implementasinya di infrastructure (Redis)."""
    def retry_after(self, email: str) -> int: ...      # detik sisa blokir, 0 = boleh mencoba
    def record_failure(self, email: str) -> None: ...
    def reset(self, email: str) -> None: ...


class PasswordHasher(Protocol):
    """Hash password satu arah. Password asli tidak pernah disimpan."""
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


class TokenService(Protocol):
    """Membuat dan membaca access token (JWT)."""
    def issue(self, user: User) -> str: ...
    def read(self, token: str) -> dict: ...
